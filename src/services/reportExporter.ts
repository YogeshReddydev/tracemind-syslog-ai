/**
 * Forensic Report Exporter
 * Generates structured Markdown, JSON bundles, and audit documentation
 */

import { Investigation } from '../types';

/**
 * Generates an executive and technical forensic investigation report in Markdown
 */
export function generateMarkdownReport(inv: Investigation): string {
  const timestamp = new Date().toISOString();
  const criticalFindings = inv.findings.filter(f => f.severity === 'critical');
  const highFindings = inv.findings.filter(f => f.severity === 'high');
  const mediumFindings = inv.findings.filter(f => f.severity === 'medium');

  return `# TRACEMIND AI — DIGITAL FORENSICS INVESTIGATION REPORT
**Case:** ${inv.name} (${inv.caseNumber})  
**Lead Investigator:** ${inv.leadAnalyst}  
**Status:** ${inv.status.toUpperCase()}  
**Generated At:** ${timestamp}  
**Analysis Engine:** ${inv.lastAnalysisMode === 'demo_rule_engine' ? 'Deterministic Rule Engine (Verifiable Local Rules)' : 'Open-Weight LLM Inference Engine'}

---

## 1. EXECUTIVE SUMMARY
${inv.summary}

### Key Case Statistics
- **Total Evidence Items Ingested:** ${inv.evidence.length}
- **Reconstructed Timeline Events:** ${inv.timeline.length}
- **Provenance Graph Entities:** ${inv.nodes.length} nodes, ${inv.edges.length} correlated edges
- **Security Findings:** ${inv.findings.length} total (${criticalFindings.length} Critical, ${highFindings.length} High, ${mediumFindings.length} Medium)

---

## 2. CHRONOLOGICAL ATTACK TIMELINE
${inv.timeline.map((event, idx) => `
### Event ${idx + 1}: ${event.eventTitle}
- **Timestamp:** ${event.timestampDisplay} (${event.timestampConfidence.toUpperCase()})
- **Severity:** ${event.severity.toUpperCase()} | **Confidence Score:** ${(event.confidenceScore * 100).toFixed(0)}%
- **Evidence Reference:** \`${event.evidenceId}\`
${event.mitreAttack ? `- **MITRE ATT&CK:** ${event.mitreAttack.id} - ${event.mitreAttack.name} (${event.mitreAttack.tactic})` : ''}
${event.isContradictory ? `> ⚠️ **TELEMETRY CONTRADICTION DETECTED:** ${event.contradictionNotes}` : ''}
- **Description:** ${event.description}
- **Entities Involved:** ${event.entities.map(e => `${e.type}:${e.value}`).join(', ')}
`).join('\n')}

---

## 3. FORENSIC FINDINGS & HYPOTHESIS TESTING
${inv.findings.map((f, idx) => `
### Finding ${idx + 1}: ${f.title}
- **Severity:** ${f.severity.toUpperCase()}
- **Analyst Disposition:** ${f.status.toUpperCase()}
- **Origin Engine:** ${f.origin === 'rule_engine' ? 'Deterministic Rule Engine' : 'Open-Weight Language Model'}
- **Confidence:** ${(f.confidenceScore * 100).toFixed(0)}% — ${f.confidenceExplanation}
- **MITRE Tactic / Technique:** ${f.mitreTactic || 'N/A'} — ${f.mitreTechnique || 'N/A'}

#### Supporting Evidence Excerpts:
${f.evidenceExcerpts.map(ex => `> [${ex.evidenceId} / ${ex.source}]: "${ex.quote}"`).join('\n\n')}

#### Reasoning Summary:
${f.reasoningSummary}

#### Competing / Alternative Benign Explanations:
${f.alternativeBenignExplanations.map(alt => `- ${alt}`).join('\n')}

#### What Would Disprove This?
- **Evidence Gaps:**
${f.whatWouldDisproveThis.evidenceGaps.map(gap => `  * ${gap}`).join('\n')}
- **Competing Hypotheses:**
${f.whatWouldDisproveThis.competingHypotheses.map(hyp => `  * ${hyp}`).join('\n')}
- **Recommended Verifications:**
${f.whatWouldDisproveThis.recommendedVerifications.map(rec => `  * ${rec}`).join('\n')}

#### Recommended Defensive Actions:
${f.recommendedDefensiveActions.map(action => `1. ${action}`).join('\n')}
`).join('\n\n---\n')}

---

## 4. INGESTED EVIDENCE INVENTORY
| ID | Source Type | Reference | Timestamp | Extracted Indicators | Status |
|----|-------------|-----------|-----------|----------------------|--------|
${inv.evidence.map(e => `| \`${e.id}\` | ${e.sourceType} | ${e.sourceReference} | ${e.timestamp || 'Uncertain'} | ${e.indicators.length} indicators | ${e.status} |`).join('\n')}

---

## 5. ANALYST INVESTIGATION NOTES
${inv.notes || 'No supplementary analyst notes recorded.'}

---
*Generated by TraceMind AI — Evidence-Driven Cyberattack Reconstruction Platform. All findings are subject to manual forensic review by qualified incident response personnel.*
`;
}

/**
 * Downloads a text file to client browser
 */
export function downloadFile(filename: string, content: string, mimeType: string): void {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
